TERM_DEFAULT_ROWS = ["> PROMPT", "", "> RENDERING...", "\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591  0%"]


def capline_step(n):
    """Per-line stagger for cap_lines, normalized so the LAST line's clock
    (wp - j*step at wp=1) stays STRICTLY > 0 — word_pop early-returns at
    appear <= 0, so step must stay under 1/(n-1). Below the nominal
    CAPLINE_LINE_STEP only when n makes it unreachable — 2 lines keep the
    shipped 0.45 (golden-safe). (audit #1: line j>=3 never drew.)"""
    if n <= 1:
        return 0.0
    return min(CAPLINE_LINE_STEP, 0.9 / (n - 1))


def clamp01(t):
    return max(0.0, min(1.0, t))


def preamble_at(k, at):
    """Kind clock preamble — must match render_layer's preamble block."""
    if k in ("panel_top", "panel_mid"):
        return at - PANEL_SHIFT
    return at


def _probe_dr():
    return ImageDraw.Draw(Image.new("RGB", (8, 8)))


COLORS_MAX = 4   # per-caption "colors" list cap (word-cycle kinds; v1.5 gate)

# v1.5 item 4: exit-clock table — the settle ramp each kind's animation uses
# on the OUTGOING side of a transition window. The renderer froze every kind's
# prog at its shot end with a hardcoded /0.32 regardless of its entrance ramp,
# so long-stagger kinds (typewriter 1.8s, pump, slam, trackin) were killed mid-
# entrance inside fades even when they settled before the cut. Table mirrors
# the engine's POP_RAMP_GATE; exit_gate() is the single source both sides read.
EXIT_CLOCK = {"typewriter": TYPE_RAMP, "pump": PUMP_RAMP,
              "slam": SLAM_RAMP, "slam_v2": SLAM_RAMP, "trackin": TRACK_RAMP}
EXIT_DEFAULT = 0.32   # shipped gate for every other kind (goldens)

# v1.5 item 4: per-caption opt-in exit motion ("exit": rise|wipe|scale).
# The exit window starts at shot_t - EXIT_RAMP and runs to the cut; a caption
# must be SETTLED before it starts moving out (checker flag kind 'exit').
EXIT_RAMP = 0.25
EXIT_KINDS = ("rise", "wipe", "scale")

# v1.5 item 6: opt-in per-caption easing ("ease": expo|elastic|steps) on the
# entrance kinds whose progress var plugs in cleanly. The ease REPLACES the
# default curve (ease_o/ease_ow) inside the same ramp window — settle clocks
# (done_at, EXIT_CLOCK) untouched, so checker parity holds by construction.
EASE_NAMES = ("expo", "elastic", "steps")
EASE_KINDS = ("accent_word", "pump", "slam", "wipe", "trackin")
# kicker's stagger is LOCKED (house rule): validate tolerates the shared field
# shape, checks.py flags ease-on-kicker so nobody ships an ignored ease.


def ease_flag(L):
    """None if the caption's `ease` field is absent/valid; else an error
    string (kind whose entrance clock can't take an ease — kicker locked)."""
    if not L.get("ease"):
        return None
    if L.get("kind") not in EASE_KINDS:
        return ("ease on kind %r unsupported (locked/no plug-in progress var; "
                "choices: %s)" % (L.get("kind"), ", ".join(EASE_KINDS)))
    return None

# v1.5 item 8: opt-in entrance FX ("fx": "glitch" = RGB-split channel
# fringe). Rides the entrance ramp ONLY: offset amplitude scales with the
# ramp's REMAINING energy (1-prog), so it settles to zero at done_at by
# construction. Host kinds must have a settle clock (measure().done_at) that
# the ramp window plugs into — checker flags fx on any other kind.
FX_NAMES = ("glitch", "track_collapse")
FX_KINDS = ("accent_word", "burst", "slam_v2")   # "big_word" family hosts
# v1.5 item 9: track_collapse — tracking starts +TRACK_COLLAPSE_PX and
# collapses to 0 over TRACK_RAMP (trackin math INVERTED). Convergent settle:
# trk=0 equals the plain kind's rest state byte-for-byte, so like slam_v2 it
# only hosts on kinds whose done_at rides TRACK_RAMP.
FX_TRACK_KINDS = ("accent_word", "title_block")
TRACK_COLLAPSE_PX = 18   # px extra tracking at entrance start (plan-locked)
GLITCH_MIN_OFF = 4       # px, floor of the channel offset while ramping
GLITCH_MAX_OFF = 12      # px, ceiling at entrance start

# --- v1.5 item 10 (C5): eq_bars — ambient equalizer strip -----------------
EQ_DEFAULT_N = 5          # bar count when omitted (plan: default 5)
EQ_MAX_N = 7              # hard cap (plan: <=7)
EQ_DEFAULT_W = 0.32       # bar width as a fraction of its slot
EQ_MIN_W, EQ_MAX_W = 0.05, 1.0   # sane fraction band (validate gates 0.05..1.5 msg)
EQ_H_FRAC = 0.16          # tallest bar as a fraction of canvas height
EQ_BEAT_CYCLES = 2.0      # per-bar sine cycles per beat (amplitude modulator)
EQ_VO_WIN = 0.05          # VO envelope: RMS window (s); precomputed ONCE/shot

# --- v1.5 C9.1 (Yasser directive): per-caption vertical placement ----------
# "place": "top" | "middle" | "bottom" retargets the caption's OWN anchor frac
# (per-kind key below) to a band value; "middle" = the kind's shipped frac
# (byte-identical). Fine-tune: "y": float 0..1 overrides the frac exactly.
# Opt-in only — no field -> render_layer passes the SHARED LY dict through,
# so every shipped project stays byte-for-byte.
PLACE_NAMES = ("top", "middle", "bottom")
PLACE_TOP_FRAC = 0.16     # band anchor for place:"top" (as fraction of H)
PLACE_BOTTOM_FRAC = 0.74  # band anchor for place:"bottom" (above eq/handle zone)
# kind -> the *_frac key its draw path reads as the vertical anchor (audited
# against captions.py draw_* sites; kinds with no frac — panel_*, cap_lines,
# chips, handle, title_block, rule_draw — reject `place` in validate: their
# geometry is a fixed plate/derived anchor, not a band choice).
PLACE_KEYS = {
    "burst": "burst_frac", "slam": "burst_frac", "slam_v2": "burst_frac",
    "pump": "burst_frac", "flashpop": "accent_frac", "wipe": "accent_frac",
    "trackin": "accent_frac", "accent_word": "accent_frac",
    "big_word": "accent_frac", "split": "accent_frac",
    "maskline": "caplines_frac", "big_number": "bignum_frac",
    "small": "small_frac", "cta": "cta_frac", "kicker": "kicker_frac",
    "terminal": "term_y_frac",
}


def place_merge(LY, L):
    """Per-caption copy of the merged shot LY with `place`/`y` applied.
    Returns LY ITSELF (no copy) when neither field is present — the shipped
    byte-identical path. Unknown kind for `place` is pre-gated by validate."""
    place, y = L.get("place"), L.get("y")
    if place is None and y is None:
        return LY
    M = dict(LY)
    if place is not None:
        key = PLACE_KEYS[L["kind"]]
        if place == "top":
            M[key] = PLACE_TOP_FRAC
        elif place == "bottom":
            M[key] = PLACE_BOTTOM_FRAC
        # "middle" -> keep the shot/preset frac (explicitly allowed no-op)
    if y is not None:
        for key in set(PLACE_KEYS.values()):
            M[key] = float(y)   # fine-tune pins this caption's anchors
    return M


def eq_bar_height(eng, L, idx, lt, g, vo_env, frame=None):
    """Height (px, >0) of bar slot `idx` at local time `lt` / global time `g`:
    an abs-sine stack seeded per bar slot, amplitude-modulated by the bed's
    beat clock (seed-time fallback when no tempo), plus the shot's VO RMS
    envelope sampled at the GLOBAL FRAME INDEX (`frame`; falls back to idx
    only if the caller passes none — it never indexes the env by bar slot).
    Pure function of (frame index, project JSON) -> sample == full renders."""
    n = int(L.get("n", EQ_DEFAULT_N))
    wfrac = float(L.get("w", EQ_DEFAULT_W))
    slot = eng.L["safe_w"] / n
    bar_w = max(4, int(wfrac * slot))
    hmax = int(EQ_H_FRAC * eng.H)
    ph = eng.beat_phase(g)
    if ph is None:
        ph = eng.fx_phase(idx)
    t = lt * EQ_BEAT_CYCLES * 2.0 * math.pi + idx * 1.7
    osc = abs(math.sin(t)) * (0.55 + 0.45 * abs(math.sin(ph * 2.0 * math.pi)))
    h = 0.18 + 0.82 * osc
    if vo_env is not None:
        f = idx if frame is None else int(frame)
        if 0 <= f < len(vo_env):
            h += 0.6 * vo_env[f]
    return bar_w, max(6, min(hmax, int(h * hmax)))



def track_collapse_px(prog):
    """Extra per-char tracking (px) for one frame: +18 -> 0 over the ramp.
    prog here is the kind's ramp-normalized progress against TRACK_RAMP;
    pure function -> sample renders == full renders."""
    return int(round(TRACK_COLLAPSE_PX * (1.0 - min(1.0, max(0.0, prog)))))


def glitch_offset(prog, phase):
    """Signed R-channel offset (px) for one frame: a sin STEP of `phase`
    (beat 0..1 or seed fallback), amplitude (4..12) scaled by the ramp's
    remaining energy. Zero once the entrance settles (prog >= 1). Pure
    function of (prog, phase) -> sample renders == full renders."""
    if prog >= 1.0:
        return 0.0
    step = math.sin(phase * 2.0 * math.pi)
    mag = GLITCH_MIN_OFF + (GLITCH_MAX_OFF - GLITCH_MIN_OFF) * abs(step)
    return math.copysign(mag * (1.0 - prog), step if step != 0.0 else 1.0)


def fx_flag(L, done_at):
    """None if the caption's `fx` field is absent/valid-for-kind; else an
    error string. Renderer and checker read this SAME eligibility rule."""
    fx = L.get("fx")
    if not fx:
        return None
    hosts = FX_TRACK_KINDS if fx == "track_collapse" else FX_KINDS
    if L.get("kind") not in hosts:
        return ("fx %r on kind %r unsupported (needs an entrance kind with a "
                "settle clock; choices: %s)"
                % (fx, L.get("kind"), ", ".join(hosts)))
    if done_at is None:
        return "fx %r but the line never settles inside the shot" % fx
    return None

# v1.5 item 5: opt-in idle motion ("idle": true) — breathe (scale sine) and
# color_wave (per-word tint pulse). House rule: the line's ONE animated
# property AFTER settle; entrance kinds untouched. Window = done_at -> exit
# start (or shot end), so an exiting caption never breathes while rising out.
IDLE_PERIOD = 3.0        # breathe sine period (s) — seed-locked phase per caption slot
IDLE_AMP = 0.02          # +/-2% scale swing (house rule: one property, subtle)
IDLE_WAVE_HZ = 1.0       # color_wave pulse rate (Hz) on per-word tints
# Kinds breathe scales cleanly (whole-element fills or word_pop draws):
IDLE_BREATHE_KINDS = ("accent_word", "cta", "small", "handle", "panel_top",
                      "panel_mid")
# Kinds whose per-word tints color_wave pulses (colors come from `colors` or
# a kind default; no entrance clock rides prog, so the wave can't distort it):
IDLE_WAVE_KINDS = ("kicker", "typewriter", "pump", "split", "maskline")


def idle_flag(L, done_at, shot_t):
    """None if the caption's `idle` field is absent/valid; else an error
    string (kind can't carry idle motion, or it never settles inside the
    shot). Renderer and checker read this SAME flag."""
    if not L.get("idle"):
        return None
    k = L.get("kind")
    if k in ("terminal", "chips", "big_number", "wipe", "flashpop", "burst"):
        return ("idle on kind %r unsupported (perpetual-motion kinds, or no "
                "clean post-settle window)" % k)
    if k not in IDLE_BREATHE_KINDS + IDLE_WAVE_KINDS:
        return "idle on unknown kind %r" % (k,)
    if done_at is None or done_at >= shot_t:
        return ("idle needs the line to settle inside the shot (%s)"
                % ("never" if done_at is None else "%.2fs >= %.2fs" % (done_at, shot_t)))
    return None


def idle_breathe(eng, cap_idx, lt):
    """Breathe scale factor at SHOT-LOCAL time `lt`: 1 +/- IDLE_AMP, period
    IDLE_PERIOD (fixed house tempo — NOT the beat clock: a `bpm` override or
    BPM.json lookup must never change what idle pixels look like). Phase is
    seed-locked to the caption slot AND rides the shot clock (not global g):
    a caption's breathe is identical whether it sits in shot 0 or shot 7, and
    pure function of (slot, lt) keeps sample renders == full renders."""
    phase = (lt / IDLE_PERIOD + 0.13 * (cap_idx[0] * 7 + cap_idx[1])) % 1.0
    return 1.0 + IDLE_AMP * math.sin(2 * math.pi * phase)


def idle_wave(eng, cap_idx, lt):
    """color_wave gain in [0,1] at SHOT-LOCAL time `lt`: per-slot seed-locked
    phase (same slot-key rule as breathe), rate IDLE_WAVE_HZ."""
    phase = (lt * IDLE_WAVE_HZ + 0.37 * (cap_idx[0] * 5 + cap_idx[1])) % 1.0
    return 0.5 + 0.5 * math.sin(2 * math.pi * phase)


def idle_done_at(k, L, eng=None):
    """Settle time for an idle-eligible kind — the renderer gate clock. MUST
    equal measure()'s m['done_at'] (checker parity by construction). Keep in
    sync with the per-kind branches; None for kinds without a model.
    `at` here is the PREAMBLE-SHIFTED clock (preamble_at), matching render_layer.
    Wrap-dependent kinds (panel_*) route through `eng.fit_panel_lines` exactly
    like measure() does — pass the rendering Engine; without one, raw lines are
    a safe LOWER bound only."""
    at = preamble_at(k, float(L.get("at", 0.2)))
    if k in ("accent_word", "cta"):
        nw = len(L.get("text", "").split(" "))
        return at + (nw - 1) * WORD_STEP + WORD_RAMP
    if k in ("small", "handle"):
        # single draw_center_text line: entrance rides the shared gated prog,
        # fully open at at+POP_RAMP; measure's generic fallback counts its
        # words through the word_pop stagger clock — take the LATER of both.
        nw = len(L.get("text", "").split(" "))
        return max(at + POP_RAMP,
                   at + max(0, nw - 1) * WORD_STEP + WORD_RAMP)
    if k in ("panel_top", "panel_mid"):
        lines = (eng.fit_panel_lines(_probe_dr(), L["lines"], eng.H1)
                 if eng is not None else L.get("lines", []))
        return _panel_settle(lines, at)
    if k == "kicker":
        nw = len(L.get("text", "").split(" "))
        return at + POP_RAMP / KICKER_RAMP * max(1.0, (nw - 1) * 0.15 + 0.45)
    if k == "typewriter":
        n = len(L.get("text", ""))
        return at + (n - 1) * TYPE_STEP + TYPE_RAMP
    if k == "pump":
        nw = len(L.get("text", "").split(" "))
        return at + (nw - 1) * PUMP_STEP + PUMP_RAMP
    if k in ("split", "maskline"):
        # split: gate fully opens at at+POP_RAMP (measure). maskline: word_pop
        # clocks on raw appear (draw_maskline), last word lands there.
        nw = len(L.get("text", "").split(" "))
        if k == "split":
            return at + POP_RAMP
        return at + (nw - 1) * WORD_STEP + WORD_RAMP
    return None


def _panel_settle(lines, at):
    """Panel word-pop settle over RAW lines (measure() fits through the engine
    first; wrapped lines only ever ADD stagger, so this is a safe lower bound)."""
    n = len(lines)
    if not n:
        return None
    nww = [len(l.split(" ")) for l in lines]
    span = max(nww) * WORD_STEP + WORD_RAMP
    Sv = (1.0 - span) / (n - 1) if n > 1 else 0.0
    worst = 0.0
    for j in range(n):
        req_j = (nww[j] - 1) * WORD_STEP + WORD_RAMP
        worst = max(worst, (req_j + j * Sv) / (span / 0.55))
    return at + PANEL_WDELAY + PANEL_WRAMP * min(worst, 1.0)


def exit_flag(L, done_at, shot_t):
    """None if the caption's `exit` field is absent/valid-and-settled; else an
    error string (unknown name, or the line never settles before its exit
    starts). Renderer and checker read this SAME flag."""
    ex = L.get("exit")
    if ex is None:
        return None
    if ex not in EXIT_KINDS:
        return "exit %r unknown (choices: %s)" % (ex, ", ".join(EXIT_KINDS))
    if done_at is None or done_at + 0.1 > shot_t - EXIT_RAMP:
        return ("exit '%s' starts at %.2fs but the line settles at %s"
                % (ex, shot_t - EXIT_RAMP,
                   "never inside the shot" if done_at is None else "%.2fs" % done_at))
    return None


def exit_gate(k):
    return EXIT_CLOCK.get(k, EXIT_DEFAULT)


def colors_flag(eng, L):
    """v1.5: shared validation for a caption's optional `colors` palette-name
    list -> error message or None. Renderer builds PAL from the SAME preset
    dict this reads, so an unknown name never silently falls back at draw
    time; >COLORS_MAX names can't cycle meaningfully on word kinds."""
    names = L.get("colors")
    if names is None:
        return None
    if not isinstance(names, list) or not names:
        return "colors must be a non-empty list of palette names"
    if len(names) > COLORS_MAX:
        return "colors list has %d names (max %d)" % (len(names), COLORS_MAX)
    pal = eng.preset.get("colors", {})
    bad = [n for n in names if not isinstance(n, str) or n not in pal]
    if bad:
        return "colors %s not in preset palette (%s)" % (
            ", ".join(map(str, bad)), ", ".join(sorted(pal)))
    return None


def measure(eng, L, k, shot_t, at_raw, avail_w=None, LY=None):
    """Per-kind measurements. Returns dict; keys vary by kind:
    lines/n, done_at (settle time), widths/total, rows_done/typing_done,
    tsize/trk, longest_word. Values equal what the draw path computes.
    v1.4 composition layer: `avail_w` = horizontal budget for a left-aligned
    run (shared-inset column); None = shipped center behavior everywhere.
    `LY` = merged per-shot layout dict (checker passes it; default falls back
    to the preset layout so the renderer path is unchanged)."""
    LY = LY if LY is not None else eng.L
    at = preamble_at(k, at_raw)
    m = {"at_eff": at}
    # v1.5: caption-level colors gate (renderer + checker agree by
    # construction; kinds read PAL built from this same preset dict).
    cf = colors_flag(eng, L)
    if cf:
        m["colors_error"] = cf

    if k in ("panel_top", "panel_mid"):
        lines = eng.fit_panel_lines(_probe_dr(), L["lines"], eng.H1, avail_w=avail_w)
        n = len(lines)
        nw = [len(l.split(" ")) for l in lines]
        span = max(nw) * WORD_STEP + WORD_RAMP
        Sv = (1.0 - span) / (n - 1) if n > 1 else 0.0
        # line j's last word lands when wprog*(span/0.55) - j*Sv >= req_j,
        # req_j = (nw_j-1)*WORD_STEP + WORD_RAMP (its OWN word run), and
        # wprog = (lt-at-PANEL_WDELAY)/PANEL_WRAMP. Per-line max replaces the
        # old (1.0 + Sv*0.55/span) form, which over-stated settle by ~0.6s
        # and produced false timing flags (audit #4, pixel-proven).
        worst = 0.0
        for j in range(n):
            req_j = (nw[j] - 1) * WORD_STEP + WORD_RAMP
            worst = max(worst, (req_j + j * Sv) / (span / 0.55))
        done_at = at + PANEL_WDELAY + PANEL_WRAMP * min(worst, 1.0)
        m.update(lines=lines, n=n, span=span, done_at=done_at)

    elif k == "cap_lines":
        cl = eng.fit_panel_lines(_probe_dr(), L["lines"], eng.BODY, avail_w=avail_w)
        # v1.31: draw path wraps too (audit #3 — checker measured wrapped
        # lines while the renderer drew RAW, so off-canvas text went unflagged).
        # line j appear = wp - j*capline_step(n); inside word_pop its last word
        # needs that >= req_j. done_at is REAL settle: wp clamps at 1, so the
        # clock needed is min(worst, 1) * CAPLINE_RAMP (audit #1/#2 — the old
        # form modelled an unreachable wp>1 and double-counted WORD math).
        n = len(cl)
        step = capline_step(n)
        worst = 0.0
        for j, l in enumerate(cl):
            req_j = (len(l.split(" ")) - 1) * WORD_STEP + WORD_RAMP
            worst = max(worst, req_j + j * step)
        done_at = at + CAPLINE_RAMP * min(worst, 1.0)
        m.update(lines=cl, n=n, done_at=done_at)

    elif k == "terminal":
        nrows = len(L.get("rows", TERM_DEFAULT_ROWS))
        rows_done = TERM_FIRST_AT + (nrows - 1) * TERM_ROW_STEP + TERM_ROW_RAMP
        typing_done = float(shot_t) - 1.0
        m.update(rows_done=rows_done, typing_done=typing_done)

    elif k == "chips":
        widths = [eng.MONOS.getlength(c) + eng.L["chip_extra_w"] for c in L["items"]]
        total = sum(widths) + eng.L["chip_gap"] * (len(L["items"]) - 1)
        done_at = at + (len(L["items"]) - 1) * CHIP_STEP + CHIP_RAMP
        m.update(widths=widths, total=total, done_at=done_at)

    elif k == "title_block":
        # v1.4 composition layer: measure with the SAME merged per-shot layout
        # the renderer draws with (a narrowed title_limit wraps the title onto
        # more lines; checker must agree by construction).
        lines, tsize, trk = eng.fit_title(_probe_dr(), L.get("text", ""),
                                          LY["logo"], LY["title_limit"])
        m.update(lines=lines, tsize=tsize, trk=trk)
        # C7: title elements (underline, sub plate) settle on the shared
        # TITLE_PLATE_K gain clock — done_at feeds the timing gate below.
        m["done_at"] = at + POP_RAMP / TITLE_PLATE_K
        if L.get("sub"):
            m["sub_lines"] = eng.fit_small_lines(_probe_dr(), L["sub"],
                                                 eng.SMALL, eng.TRK.get("sub", 0))

    elif k == "small":
        wl = max(L.get("text", "").split(" "),
                 key=lambda w: eng.SMALL.getlength(w), default="")
        m.update(longest_word=wl)

    elif k == "kicker":
        # staggered word rise: ep reaches 1 at POP_RAMP/KICKER_RAMP; the last
        # word (i=nw-1) needs ep >= (nw-1)*0.15 + 0.45 to fully settle
        nw = len(L.get("text", "").split(" "))
        done_at = at + POP_RAMP / KICKER_RAMP * max(1.0, (nw - 1) * 0.15 + 0.45)
        m.update(done_at=done_at)

    elif k == "typewriter":
        # per-character reveal: char i appears when tp >= i*TYPE_STEP/TYPE_RAMP...
        # exactly, draw path uses tc = (tp - i*TYPE_STEP)/TYPE_RATE; the last
        # char settles at tp = (n-1)*TYPE_STEP + TYPE_RAMP -> done_at below.
        n = len(L.get("text", ""))
        done_at = at + (n - 1) * TYPE_STEP + TYPE_RAMP
        m.update(done_at=done_at, nchars=n)

    elif k == "pump":
        # per-word scale punch: word i settles at
        # at + PUMP_RAMP*(1 + i*PUMP_STEP/PUMP_RAMP); last word is the max.
        nw = len(L.get("text", "").split(" "))
        done_at = at + (nw - 1) * PUMP_STEP + PUMP_RAMP
        m.update(done_at=done_at)

    # --- v1.4 kinetic drafts: settle clocks mirror captions.py exactly ------
    elif k == "wipe":
        # mask edge sweeps on prog*WIPE_K (draw_wipe); full reveal at prog=1/WIPE_K
        done_at = at + POP_RAMP / WIPE_K
        m.update(done_at=done_at)

    elif k == "split":
        # halves settle with ease_o(prog): offset ~0 when prog>=~0.95; the
        # shared gate fully opens at at+POP_RAMP -> settle there.
        done_at = at + POP_RAMP
        m.update(done_at=done_at)

    elif k in ("slam", "slam_v2"):
        # scale settles when sp = clamp01(prog/SLAM_RAMP*POP_RAMP) hits 1,
        # i.e. prog >= SLAM_RAMP/POP_RAMP -> lt = at + SLAM_RAMP. slam_v2's
        # squash-stretch rides the SAME clock (lands at sp=1), so the settle
        # family is shared by construction.
        done_at = at + SLAM_RAMP
        m.update(done_at=done_at)

    elif k == "trackin":
        # tracking closes when tp hits 1 -> lt = at + TRACK_RAMP
        done_at = at + TRACK_RAMP
        m.update(done_at=done_at)

    elif k == "rule_draw":
        # v1.5 item 9: standalone accent rule, draws left->right over the
        # generic POP_RAMP gate (single-beat family). Width is L["w"] as a
        # fraction of safe_w, or the measured text width when text is given.
        done_at = at + POP_RAMP
        wfrac = float(L.get("w", 0.4))
        if not (0.05 <= wfrac <= 1.0):
            m["error"] = "rule_draw w must be a fraction 0.05..1.0 (got %r)" % L.get("w")
        m.update(done_at=done_at, rule_w=int(wfrac * (m.get("avail_w") or 999)))

    elif k == "eq_bars":
        # v1.5 item 10 (C5): ambient equalizer strip — ALWAYS animating, so
        # like terminal/chips there is NO settle clock (the generic word-pop
        # fallback below must not fire: no text/lines keys here anyway, and
        # the kind list excludes it). Shape gates mirror validate_project.
        n = int(L.get("n", EQ_DEFAULT_N))
        wfrac = float(L.get("w", EQ_DEFAULT_W))
        if not (1 <= n <= EQ_MAX_N):
            m["error"] = "eq_bars n must be 1..%d (got %r)" % (EQ_MAX_N, L.get("n"))
        elif not (EQ_MIN_W < wfrac < 1.5):
            m["error"] = "eq_bars w must be a fraction 0.05..<1.5 (got %r)" % L.get("w")

    elif k == "flashpop":
        nw = len(L.get("text", "").split(" "))
        done_at = at + (nw - 1) * FLASH_STEP + FLASH_RAMP
        m.update(done_at=done_at)

    elif k == "maskline":
        # word stagger mirrors word_pop clocks (WORD_STEP/WORD_RAMP)
        nw = len(L.get("text", "").split(" "))
        done_at = at + (nw - 1) * WORD_STEP + WORD_RAMP
        m.update(done_at=done_at, nwords=nw)

    # v1.5 item 4: word_pop-based kinds (accent_word/cta/small/handle/kicker/
    # title sub...) have no per-kind branch above; give them the generic pop
    # settle so exit_flag has a done_at to gate against. WORD math matches
    # engine.word_pop's stagger (0.18 step / 0.36 ramp = WORD_STEP/WORD_RAMP).
    if "done_at" not in m and k not in ("terminal", "chips") \
            and ("text" in L or "lines" in L):
        nw = len((L.get("text") or " ".join(L.get("lines") or [])).split(" "))
        m["done_at"] = at + max(0, nw - 1) * WORD_STEP + WORD_RAMP

    return m
