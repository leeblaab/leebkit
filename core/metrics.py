"""core/metrics.py — per-kind measure() (v1.3 C4).

checks.py must never re-derive layout/timing math by mirroring render_layer
formulas — that drift already bit us twice (panel preamble missing from the
checker; cap_lines checked on raw instead of wrapped lines). Each kind's
measure() returns the SAME numbers its captions.py draw path computes at
draw time; checks assert on these. Renderer and checker agree by
construction.

done_at semantics (agreed v1.3): SETTLE TIME — the moment the last animated
element reaches progress 1 (same meaning as today's timing flags). The
storyboard strip keeps its fixed 0.75*shot_t sampling in v1.3; revisiting
sampling vs done_at is a v1.4 decision.

C4 scope: constants here are the single source for stagger clocks. captions.py
draw functions import them so a formula change lands in BOTH paths at once.
The Engine-level metrics cache (fit/wrap computed once per caption instead of
per frame) ships as C3b on top of this module."""

from PIL import Image, ImageDraw

# --- shared clock constants: SINGLE source for stagger math ---------------
PANEL_SHIFT = 0.45      # panel_* early-start preamble (C2)
POP_RAMP = 0.32         # generic prog ramp after `at` (render_layer gate)
PANEL_WDELAY = 0.28     # word-pop start delay inside panels
PANEL_WRAMP = 0.95      # word-pop progress ramp
WORD_STEP = 0.18        # per-word stagger step (word_pop)
WORD_RAMP = 0.36        # per-word appear ramp (word_pop)
CAPLINE_RAMP = 0.3      # cap_lines wp = (lt-at)/0.3
CAPLINE_LINE_STEP = 0.45    # nominal; capline_step(n) NORMALIZES it so the
                            # last of n lines is always reachable (v1.31 #1:
                            # with the raw constant, line j>=3 never drew —
                            # wp clamps at 1 and slot 3's clock was -0.35)
CHIP_STEP = 0.35
CHIP_RAMP = 0.4
KICKER_RAMP = 0.6       # v1.4 C4e: kicker word stagger (ep = prog/KICKER_RAMP)
TITLE_PLATE_K = 1.3     # title_block element clock gain (C7): the sub-plate
                        # alpha AND underline growth share ONE settle —
                        # done_at = at + POP_RAMP/TITLE_PLATE_K. Was a private
                        # prog*1.3 in draw_title_block for the plate while the
                        # underline ran raw prog (element-clock spread).
TITLE_RISE_PX = 24      # C7: back-out overshoot rise for the whole title block
                        # (ease_ow, same curve as word_pop) at the 1080 tier;
                        # scales via layout S. External typography review.
# --- v1.36 Onyx draft: typewriter / pump / tint clocks --------------------
TYPE_STEP = 0.085       # typewriter: per-character step (letters AND spaces)
TYPE_RAMP = 0.10        # per-character appear ramp
PUMP_STEP = 0.24        # word pump: per-word stagger
PUMP_KICK = 1.30        # word pump: scale punch peak (word_pump)
PUMP_RAMP = 0.30        # word pump: per-word progress ramp
# --- v1.4 kinetic drafts: mask-wipe / split-slide / slam / track-in / flash --
SLAM_RAMP = 0.26        # slam: scale-down-from-overscan settle ramp
SLAM_FROM = 1.85        # slam: start scale (text "falls into" the frame)
SPLIT_RAMP = 0.34       # split: half-lines slide-to-center ramp
TRACK_RAMP = 0.55       # trackin: tracking-expand settle ramp
FLASH_STEP = 0.16       # flashpop: per-word stagger
FLASH_RAMP = 0.22       # flashpop: per-word ramp (peak alpha mid-ramp)
WIPE_K = 1.4            # mask-wipe: prog gain (done_at = at + POP_RAMP/WIPE_K)
TERM_FIRST_AT = 0.4     # terminal first row at lt=0.4 (kind clock, not `at`)
TERM_ROW_STEP = 0.5
TERM_ROW_RAMP = 0.3
# default terminal rows — SINGLE source (audit #8: metrics defaulted to 3
# rows, captions.draw_terminal drew 4 incl. the auto bar row -> checker and
# renderer disagreed). The bar row is auto-generated by draw_terminal when a
# row matches _bar_row; kept in the default so rows_done covers it.
TERM_DEFAULT_ROWS = ["> PROMPT", "", "> RENDERING...", "\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591\u2591  0%"]


def capline_step(n):
    """Per-line stagger for cap_lines, normalized so the LAST line's clock
    (wp - j*step at wp=1) stays STRICTLY > 0 — word_pop early-returns at
    appear <= 0, so step must stay under 1/(n-1). Below the nominal
    CAPLINE_LINE_STEP only when n makes it unreachable — 2 lines keep the
    shipped 0.45 (golden-safe). (audit #1: line j>=3 never drew.)"""
    if n <= 1:
        return 0.0
    return min(CAPLINE_LINE_STEP, 0.9 / (n - 1))


def clamp01(t):
    return max(0.0, min(1.0, t))


def preamble_at(k, at):
    """Kind clock preamble — must match render_layer's preamble block."""
    if k in ("panel_top", "panel_mid"):
        return at - PANEL_SHIFT
    return at


def _probe_dr():
    return ImageDraw.Draw(Image.new("RGB", (8, 8)))


def measure(eng, L, k, shot_t, at_raw):
    """Per-kind measurements. Returns dict; keys vary by kind:
    lines/n, done_at (settle time), widths/total, rows_done/typing_done,
    tsize/trk, longest_word. Values equal what the draw path computes."""
    at = preamble_at(k, at_raw)
    m = {"at_eff": at}

    if k in ("panel_top", "panel_mid"):
        lines = eng.fit_panel_lines(_probe_dr(), L["lines"], eng.H1)
        n = len(lines)
        nw = [len(l.split(" ")) for l in lines]
        span = max(nw) * WORD_STEP + WORD_RAMP
        Sv = (1.0 - span) / (n - 1) if n > 1 else 0.0
        # line j's last word lands when wprog*(span/0.55) - j*Sv >= req_j,
        # req_j = (nw_j-1)*WORD_STEP + WORD_RAMP (its OWN word run), and
        # wprog = (lt-at-PANEL_WDELAY)/PANEL_WRAMP. Per-line max replaces the
        # old (1.0 + Sv*0.55/span) form, which over-stated settle by ~0.6s
        # and produced false timing flags (audit #4, pixel-proven).
        worst = 0.0
        for j in range(n):
            req_j = (nw[j] - 1) * WORD_STEP + WORD_RAMP
            worst = max(worst, (req_j + j * Sv) / (span / 0.55))
        done_at = at + PANEL_WDELAY + PANEL_WRAMP * min(worst, 1.0)
        m.update(lines=lines, n=n, span=span, done_at=done_at)

    elif k == "cap_lines":
        cl = eng.fit_panel_lines(_probe_dr(), L["lines"], eng.BODY)
        # v1.31: draw path wraps too (audit #3 — checker measured wrapped
        # lines while the renderer drew RAW, so off-canvas text went unflagged).
        # line j appear = wp - j*capline_step(n); inside word_pop its last word
        # needs that >= req_j. done_at is REAL settle: wp clamps at 1, so the
        # clock needed is min(worst, 1) * CAPLINE_RAMP (audit #1/#2 — the old
        # form modelled an unreachable wp>1 and double-counted WORD math).
        n = len(cl)
        step = capline_step(n)
        worst = 0.0
        for j, l in enumerate(cl):
            req_j = (len(l.split(" ")) - 1) * WORD_STEP + WORD_RAMP
            worst = max(worst, req_j + j * step)
        done_at = at + CAPLINE_RAMP * min(worst, 1.0)
        m.update(lines=cl, n=n, done_at=done_at)

    elif k == "terminal":
        nrows = len(L.get("rows", TERM_DEFAULT_ROWS))
        rows_done = TERM_FIRST_AT + (nrows - 1) * TERM_ROW_STEP + TERM_ROW_RAMP
        typing_done = float(shot_t) - 1.0
        m.update(rows_done=rows_done, typing_done=typing_done)

    elif k == "chips":
        widths = [eng.MONOS.getlength(c) + eng.L["chip_extra_w"] for c in L["items"]]
        total = sum(widths) + eng.L["chip_gap"] * (len(L["items"]) - 1)
        done_at = at + (len(L["items"]) - 1) * CHIP_STEP + CHIP_RAMP
        m.update(widths=widths, total=total, done_at=done_at)

    elif k == "title_block":
        lines, tsize, trk = eng.fit_title(_probe_dr(), L.get("text", ""),
                                          eng.L["logo"], eng.L["title_limit"])
        m.update(lines=lines, tsize=tsize, trk=trk)
        # C7: title elements (underline, sub plate) settle on the shared
        # TITLE_PLATE_K gain clock — done_at feeds the timing gate below.
        m["done_at"] = at + POP_RAMP / TITLE_PLATE_K
        if L.get("sub"):
            m["sub_lines"] = eng.fit_small_lines(_probe_dr(), L["sub"],
                                                 eng.SMALL, eng.TRK.get("sub", 0))

    elif k == "small":
        wl = max(L.get("text", "").split(" "),
                 key=lambda w: eng.SMALL.getlength(w), default="")
        m.update(longest_word=wl)

    elif k == "kicker":
        # staggered word rise: ep reaches 1 at POP_RAMP/KICKER_RAMP; the last
        # word (i=nw-1) needs ep >= (nw-1)*0.15 + 0.45 to fully settle
        nw = len(L.get("text", "").split(" "))
        done_at = at + POP_RAMP / KICKER_RAMP * max(1.0, (nw - 1) * 0.15 + 0.45)
        m.update(done_at=done_at)

    elif k == "typewriter":
        # per-character reveal: char i appears when tp >= i*TYPE_STEP/TYPE_RAMP...
        # exactly, draw path uses tc = (tp - i*TYPE_STEP)/TYPE_RATE; the last
        # char settles at tp = (n-1)*TYPE_STEP + TYPE_RAMP -> done_at below.
        n = len(L.get("text", ""))
        done_at = at + (n - 1) * TYPE_STEP + TYPE_RAMP
        m.update(done_at=done_at, nchars=n)

    elif k == "pump":
        # per-word scale punch: word i settles at
        # at + PUMP_RAMP*(1 + i*PUMP_STEP/PUMP_RAMP); last word is the max.
        nw = len(L.get("text", "").split(" "))
        done_at = at + (nw - 1) * PUMP_STEP + PUMP_RAMP
        m.update(done_at=done_at)

    # --- v1.4 kinetic drafts: settle clocks mirror captions.py exactly ------
    elif k == "wipe":
        # mask edge sweeps on prog*WIPE_K (draw_wipe); full reveal at prog=1/WIPE_K
        done_at = at + POP_RAMP / WIPE_K
        m.update(done_at=done_at)

    elif k == "split":
        # halves settle with ease_o(prog): offset ~0 when prog>=~0.95; the
        # shared gate fully opens at at+POP_RAMP -> settle there.
        done_at = at + POP_RAMP
        m.update(done_at=done_at)

    elif k == "slam":
        # scale settles when sp = clamp01(prog/SLAM_RAMP*POP_RAMP) hits 1,
        # i.e. prog >= SLAM_RAMP/POP_RAMP -> lt = at + SLAM_RAMP
        done_at = at + SLAM_RAMP
        m.update(done_at=done_at)

    elif k == "trackin":
        # tracking closes when tp hits 1 -> lt = at + TRACK_RAMP
        done_at = at + TRACK_RAMP
        m.update(done_at=done_at)

    elif k == "flashpop":
        nw = len(L.get("text", "").split(" "))
        done_at = at + (nw - 1) * FLASH_STEP + FLASH_RAMP
        m.update(done_at=done_at)

    elif k == "maskline":
        # word stagger mirrors word_pop clocks (WORD_STEP/WORD_RAMP)
        nw = len(L.get("text", "").split(" "))
        done_at = at + (nw - 1) * WORD_STEP + WORD_RAMP
        m.update(done_at=done_at, nwords=nw)

    return m
